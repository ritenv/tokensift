// Fetches LiteLLM's model pricing table and writes a curated, filtered
// snapshot to src/pricing-data.ts. Manual/explicit only, matching this
// project's policy of never making a network call automatically: run this
// yourself with `pnpm pricing:update` when you want fresher prices, it's
// never invoked by build/test/CI.
//
