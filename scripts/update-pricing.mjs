import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE_URL =
  "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json";

// Kept in sync by hand with src/encoders/registry.ts (OPENAI_MODEL_FAMILY)
// and src/encoders/anthropic-calibration.ts (ANTHROPIC_CALIBRATIONS): only
// pull pricing for models tokensift actually resolves an encoder for.
const SUPPORTED_MODELS = [
  "gpt-4o",
  "gpt-4o-mini",
  "gpt-4.1",
  "gpt-4-turbo",
  "gpt-4",
  "gpt-3.5-turbo",
  "claude-opus-4-5",
  "claude-sonnet-4-5",
  "claude-haiku-4-5",
];

async function main() {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`fetch failed: ${res.status} ${res.statusText}`);
  const raw = await res.json();

  const rows = {};
  const missing = [];
  for (const model of SUPPORTED_MODELS) {
    const entry = raw[model];
    if (!entry || typeof entry.input_cost_per_token !== "number") {
      missing.push(model);
      continue;
    }
    rows[model] = {
      model,
      provider: entry.litellm_provider ?? "unknown",
      inputCostPerToken: entry.input_cost_per_token,
      outputCostPerToken: entry.output_cost_per_token ?? 0,
      ...(typeof entry.cache_read_input_token_cost === "number"
        ? { cacheReadInputCostPerToken: entry.cache_read_input_token_cost }
        : {}),
    };
  }

  if (missing.length > 0) {
    throw new Error(`LiteLLM data missing for supported models: ${missing.join(", ")}`);
  }

  const outPath = fileURLToPath(new URL("../src/pricing-data.ts", import.meta.url));
  const body = `import type { PricingRow } from "./pricing.js";

// Curated snapshot of LiteLLM's model pricing table, filtered to the models
// tokensift resolves an encoder for. Source: BerriAI/litellm (MIT), see
// LICENSE-THIRD-PARTY.md. Generated by scripts/update-pricing.mjs, not
// hand-tuned. Refresh with \`pnpm pricing:update\`.
//
// Snapshot date: ${new Date().toISOString()}
export const PRICING_DATA: Record<string, PricingRow> = ${JSON.stringify(rows, null, 2)};
`;

  writeFileSync(outPath, body);
  console.log(`wrote pricing data for ${Object.keys(rows).length} models to ${outPath}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
